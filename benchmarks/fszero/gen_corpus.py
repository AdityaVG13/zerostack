#!/usr/bin/env python3
"""Deterministic synthetic corpus generator for index-scaling runs.

Produces exactly N rust-like source files (~1-3 KB each: imports, fn defs,
call sites) spread across nested module directories. Seeded, so any run of
this script reproduces the identical corpus byte-for-byte — corpora are
generated by committed script, never hand-curated (docs/benchmark-integrity.md).
"""
from __future__ import annotations

import argparse
import random
from pathlib import Path

WORDS = (
    "alpha bravo charlie delta echo foxtrot golf hotel india juliet kilo lima "
    "mike november oscar papa quebec romeo sierra tango uniform victor whiskey "
    "xray yankee zulu parse index store walk merge commit journal blob ref"
).split()


def gen_file(rng: random.Random, module: str, idx: int) -> str:
    lines: list[str] = [f"//! Synthetic module {module}, file {idx}.", ""]
    for _ in range(rng.randint(1, 4)):
        lines.append(f"use crate::{rng.choice(WORDS)}::{rng.choice(WORDS)};")
    lines.append("")
    n_fns = rng.randint(3, 8)
    fn_names = [f"{rng.choice(WORDS)}_{rng.choice(WORDS)}_{rng.randint(0, 999)}" for _ in range(n_fns)]
    for name in fn_names:
        lines.append(f"pub fn {name}(input: &str) -> usize {{")
        for _ in range(rng.randint(2, 8)):
            a, b = rng.choice(WORDS), rng.randint(1, 9999)
            lines.append(f"    let {a} = input.len().wrapping_add({b});")
        callee = rng.choice(fn_names)
        lines.append(f"    // calls {callee}(...) downstream")
        lines.append(f"    {callee}_helper(input.len())")
        lines.append("}")
        lines.append(f"fn {name}_helper(n: usize) -> usize {{ n.wrapping_mul(31) }}")
        lines.append("")
    return "\n".join(lines) + "\n"


def generate(out: Path, files: int, seed: int) -> None:
    rng = random.Random(seed)
    out.mkdir(parents=True, exist_ok=True)
    # ~40 files per leaf module, two directory levels: mod_XX/sub_YY/f_ZZZ.rs
    per_leaf = 40
    written = 0
    leaf = 0
    while written < files:
        top = f"mod_{leaf // 32:03d}"
        sub = f"sub_{leaf % 32:03d}"
        d = out / top / sub
        d.mkdir(parents=True, exist_ok=True)
        for i in range(min(per_leaf, files - written)):
            (d / f"f_{i:03d}.rs").write_text(gen_file(rng, f"{top}::{sub}", i))
            written += 1
        leaf += 1
    print(f"generated {written} files under {out}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--files", type=int, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--seed", type=int, default=42)
    args = ap.parse_args()
    generate(args.out, args.files, args.seed)


if __name__ == "__main__":
    main()
