# ---------------------------------------------------------------- questions

@dataclass
class Question:
    qid: str
    kind: str          # "defs" | "callers" | "literal"
    needle: str        # fn name, symbol, or literal string
    expected: str      # ground-truth relative file path (posix)


def build_questions(corpus: Path) -> list[Question]:
    """Seeded question set derived from the corpus structure -- not hand-tuned.

    defs/callers: fn names defined in exactly one file (helper included);
    literals: full `let X = input.len().wrapping_add(N);` statement lines
    occurring in exactly one file (bare `wrapping_add(N)` has only 9999
    distinct values, so at >=23k files none is unique to a single file).
    """
    fn_files: dict[str, set[str]] = {}
    call_files: dict[str, set[str]] = {}
    lit_files: dict[str, set[str]] = {}
    for f in sorted(corpus.rglob("*.rs")):
        rel = f.relative_to(corpus).as_posix()
        text = f.read_text()
        for m in re.finditer(r"^(?:pub )?fn (\w+)\(", text, re.M):
            fn_files.setdefault(m.group(1), set()).add(rel)
        # Call sites are indented; definitions start at column 0.
        for m in re.finditer(r"^\s+(\w+_helper)\(", text, re.M):
            call_files.setdefault(m.group(1), set()).add(rel)
        for m in re.finditer(r"^\s*(let \w+ = input\.len\(\)\.wrapping_add\(\d+\);)$", text, re.M):
            lit_files.setdefault(m.group(1), set()).add(rel)

    def unique(d: dict[str, set[str]]) -> list[str]:
        return sorted(k for k, v in d.items() if len(v) == 1)

    # defs/callers pool: fn unique to one file, its helper defined in that
    # same file AND actually called there (a never-called helper would make
    # "which file calls X" unanswerable).
    eligible_fns = [
        n for n in unique(fn_files)
        if len(fn_files.get(f"{n}_helper", set())) == 1
        and fn_files[f"{n}_helper"] == fn_files[n]
        and call_files.get(f"{n}_helper", set()) == fn_files[n]
    ]
    eligible_lits = unique(lit_files)
    if len(eligible_fns) < N_DEFS + N_CALLERS or len(eligible_lits) < N_LITERALS:
        raise SystemExit(
            f"INTEGRITY: question pools too small (fns={len(eligible_fns)}, "
            f"literals={len(eligible_lits)}) -- refusing to hand-pick"
        )
    rng = random.Random(SEED)
    picked_fns = rng.sample(eligible_fns, N_DEFS + N_CALLERS)
    picked_lits = rng.sample(eligible_lits, N_LITERALS)

    qs: list[Question] = []
    for i, name in enumerate(picked_fns[:N_DEFS]):
        qs.append(Question(f"defs-{i}", "defs", name, next(iter(fn_files[name]))))
    for i, name in enumerate(picked_fns[N_DEFS:]):
        sym = f"{name}_helper"
        qs.append(Question(f"callers-{i}", "callers", sym, next(iter(fn_files[sym]))))
    for i, lit in enumerate(picked_lits):
        qs.append(Question(f"literal-{i}", "literal", lit, next(iter(lit_files[lit]))))
    return qs


@dataclass
class Answer:
    qid: str
    kind: str
    wall_s: float
    bytes: int
    correct: bool
    error: str | None = None


def grade(q: Question, text: str) -> bool:
    return q.expected in text


# ---------------------------------------------------------------- baselines

def run_rg(corpus: Path, q: Question) -> Answer:
    pattern = {
        "defs": f"fn {q.needle}(",
        "callers": f"{q.needle}(",
        "literal": q.needle,
    }[q.kind]
    t0 = time.perf_counter()
    try:
        r = subprocess.run(
            ["rg", "-nF", "--", pattern, "."],
            capture_output=True, text=True, cwd=corpus, timeout=QUERY_TIMEOUT_S,
        )
        wall = time.perf_counter() - t0
        if r.returncode > 1:
            return Answer(q.qid, q.kind, wall, 0, False, f"rg rc={r.returncode}: {r.stderr[:200]}")
        return Answer(q.qid, q.kind, wall, len(r.stdout.encode()), grade(q, r.stdout))
    except subprocess.TimeoutExpired:
        return Answer(q.qid, q.kind, time.perf_counter() - t0, 0, False, "timeout")


def run_grep(corpus: Path, q: Question) -> Answer:
    pattern = {
        "defs": f"fn {q.needle}(",
        "callers": f"{q.needle}(",
        "literal": q.needle,
    }[q.kind]
    t0 = time.perf_counter()
    try:
        r = subprocess.run(
            [GREP_BIN, "-rnF", "-e", pattern, "."],
            capture_output=True, text=True, cwd=corpus, timeout=QUERY_TIMEOUT_S,
        )
        wall = time.perf_counter() - t0
        if r.returncode > 1:
            return Answer(q.qid, q.kind, wall, 0, False, f"grep rc={r.returncode}: {r.stderr[:200]}")
        return Answer(q.qid, q.kind, wall, len(r.stdout.encode()), grade(q, r.stdout))
    except subprocess.TimeoutExpired:
        return Answer(q.qid, q.kind, time.perf_counter() - t0, 0, False, "timeout")


class FffTool:
    """fff via its official Python SDK (in-process, warm index)."""

    def __init__(self, corpus: Path) -> None:
        from fff import FileFinder

        t0 = time.perf_counter()
        self.finder = FileFinder(str(corpus), watch=False)
        self.finder.wait_for_scan_blocking(timeout_ms=600_000)
        self.scan_s = time.perf_counter() - t0

    def run(self, q: Question) -> Answer:
        pattern = {
            "defs": f"fn {q.needle}(",
            "callers": f"{q.needle}(",
            "literal": q.needle,
        }[q.kind]
        t0 = time.perf_counter()
        try:
            res = self.finder.grep(pattern, mode="plain")
            lines = [
                f"{m.relative_path}:{m.line_number}: {m.line_content}"
                for m in res.items
            ]
            text = "\n".join(lines)
            wall = time.perf_counter() - t0
            return Answer(q.qid, q.kind, wall, len(text.encode()), grade(q, text))
        except Exception as e:
            return Answer(q.qid, q.kind, time.perf_counter() - t0, 0, False, f"fff: {e!r}")

    def close(self) -> None:
        self.finder.close()


TOKEN_RE = re.compile(r"[a-z0-9]+")


def bm25_tokens(text: str) -> list[str]:
    return TOKEN_RE.findall(text.lower())


class Bm25Rag:
    """Lexical code-RAG baseline: rank-bm25 over 40-line file chunks."""

    CHUNK_LINES = 40

    def __init__(self, corpus: Path) -> None:
        from rank_bm25 import BM25Okapi

        t0 = time.perf_counter()
        self.chunks: list[tuple[str, str]] = []  # (rel_path, chunk_text)
        for f in sorted(corpus.rglob("*.rs")):
            rel = f.relative_to(corpus).as_posix()
            lines = f.read_text().splitlines()
            for i in range(0, len(lines), self.CHUNK_LINES):
                self.chunks.append((rel, "\n".join(lines[i:i + self.CHUNK_LINES])))
        self.bm25 = BM25Okapi([bm25_tokens(c[1]) for c in self.chunks])
        self.build_s = time.perf_counter() - t0

    def run(self, q: Question) -> Answer:
        query = {
            "defs": f"fn {q.needle}",
            "callers": q.needle,
            "literal": q.needle,
        }[q.kind]
        t0 = time.perf_counter()
        try:
            scores = self.bm25.get_scores(bm25_tokens(query))
            top = sorted(range(len(scores)), key=lambda i: scores[i], reverse=True)[:BM25_TOP_K]
            text = "\n\n".join(f"# {self.chunks[i][0]}\n{self.chunks[i][1]}" for i in top)
            wall = time.perf_counter() - t0
            return Answer(q.qid, q.kind, wall, len(text.encode()), grade(q, text))
        except Exception as e:
            return Answer(q.qid, q.kind, time.perf_counter() - t0, 0, False, f"bm25: {e!r}")


# ---------------------------------------------------------------- fszero

def fszero_env(corpus: Path, n_files: int, **extra: str) -> dict[str, str]:
    env = os.environ.copy()
    for k in ("FSZERO_SKIP_STARTUP_INDEX", "FSZERO_SKIP_GITIGNORE",
              "ZEROSTACK_STORE_ROOT", "ZERO_STACK_STORE_ROOT",
              "FSZERO_STARTUP_INDEX", "FSZERO_INDEX_PHASES"):
        env.pop(k, None)
    env.update({
        "FSZERO_ROOT": str(corpus),
        "FSZERO_INDEX_MAX_FILES": str(n_files + 1000),
    })
    env.update(extra)
    return env


def fszero_clear_stores(corpus: Path) -> None:
    for store in (".fszero", ".zerostack", ".asgrep"):
        shutil.rmtree(corpus / store, ignore_errors=True)


def fszero_cold_index(corpus: Path, n_files: int, timeout_s: float) -> dict:
    """ONE cold index build with per-phase attribution; integrity-verified."""
    fszero_clear_stores(corpus)
    env = fszero_env(corpus, n_files, FSZERO_STARTUP_INDEX="1", FSZERO_INDEX_PHASES="1")
    t0 = time.perf_counter()
    try:
        r = subprocess.run(
            [fszero_bin(), "codemode", "return{ok:true}", "--root", str(corpus)],
            capture_output=True, text=True, timeout=timeout_s, cwd=corpus, env=env,
        )
    except subprocess.TimeoutExpired:
        return {"timeout": True, "timeout_s": timeout_s,
                "wall_s": time.perf_counter() - t0}
    wall = time.perf_counter() - t0
    ack = r.stdout.strip().splitlines()[0] if r.stdout.strip() else ""
    if r.returncode != 0 or ack.startswith("X0"):
        raise SystemExit(f"INTEGRITY: fszero cold run failed (ack={ack}) at N={n_files}")
    phase_line = next(
        (line for line in r.stderr.splitlines() if line.startswith('{"index_phases_ms"')), None)
    if phase_line is None:
        raise SystemExit(f"INTEGRITY: no phase JSON on stderr at N={n_files}")
    data = json.loads(phase_line)
    counts = data["counts"]
    if counts["files_walked"] != n_files:
        raise SystemExit(
            f"INTEGRITY: files_walked={counts['files_walked']} != N={n_files} -- refusing to publish")
    if counts["incremental"]:
        raise SystemExit(f"INTEGRITY: cold run at N={n_files} was warm")
    data["wall_s"] = wall
    return data


class FszeroServer:
    """Long-lived `fszero --mode=codemode` MCP stdio server (agent surface)."""

    def __init__(self, corpus: Path, n_files: int) -> None:
        t0 = time.perf_counter()
        self.proc = subprocess.Popen(
            [fszero_bin(), "--mode=codemode"],
            stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
            text=True, env=fszero_env(corpus, n_files), cwd=corpus,
        )
        self._id = 0
        self.rpc({"jsonrpc": "2.0", "id": self.next_id(), "method": "initialize",
                  "params": {"protocolVersion": "2024-11-05", "capabilities": {},
                             "clientInfo": {"name": "bakeoff", "version": "0"}}})
        assert self.proc.stdin is not None
        self.proc.stdin.write(json.dumps(
            {"jsonrpc": "2.0", "method": "notifications/initialized"}) + "\n")
        self.proc.stdin.flush()
        self.start_s = time.perf_counter() - t0

    def next_id(self) -> int:
        self._id += 1
        return self._id

    def rpc(self, req: dict, timeout_s: float = RPC_READ_TIMEOUT_S) -> tuple[dict, int]:
        assert self.proc.stdin is not None and self.proc.stdout is not None
        self.proc.stdin.write(json.dumps(req) + "\n")
        self.proc.stdin.flush()
        ready, _, _ = select.select([self.proc.stdout], [], [], timeout_s)
        if not ready:
            raise TimeoutError(f"fszero rpc read timeout after {timeout_s}s")
        line = self.proc.stdout.readline()
        return json.loads(line), len(line.encode())

    def execute(self, plan: str, timeout_s: float = RPC_READ_TIMEOUT_S) -> tuple[dict, int]:
        return self.rpc({"jsonrpc": "2.0", "id": self.next_id(), "method": "tools/call",
                         "params": {"name": "fz_execute_code", "arguments": {"plan": plan}}},
                        timeout_s=timeout_s)

    def run(self, q: Question) -> Answer:
        plan = fszero_plan(q)
        t0 = time.perf_counter()
        try:
            resp, nbytes = self.execute(plan)
            wall = time.perf_counter() - t0
            text = json.dumps(resp)
            return Answer(q.qid, q.kind, wall, nbytes, grade(q, text))
        except Exception as e:
            return Answer(q.qid, q.kind, time.perf_counter() - t0, 0, False, f"fszero: {e!r}")

    def close(self) -> None:
        try:
            if self.proc.stdin:
                self.proc.stdin.close()
            self.proc.wait(timeout=15)
        except Exception:
            self.proc.kill()


def fszero_plan(q: Question) -> str:
    query = {
        "defs": f"defs:{q.needle}",
        "callers": f"callers:{q.needle}",
        "literal": q.needle,
    }[q.kind]
    return (f"const r = await fs.search({{ query: {json.dumps(query)} }}); "
            "return { hits: r.payload }")


def run_fszero_spawn(corpus: Path, n_files: int, q: Question) -> Answer:
    """Fresh fszero process per query (parity with the rg/grep spawn model)."""
    t0 = time.perf_counter()
    try:
        server = FszeroServer(corpus, n_files)
    except Exception as e:
        return Answer(q.qid, q.kind, time.perf_counter() - t0, 0, False, f"spawn: {e!r}")
    try:
        resp, nbytes = server.execute(fszero_plan(q))
        wall = time.perf_counter() - t0
        return Answer(q.qid, q.kind, wall, nbytes, grade(q, json.dumps(resp)))
    except Exception as e:
        return Answer(q.qid, q.kind, time.perf_counter() - t0, 0, False, f"fszero: {e!r}")
    finally:
        server.close()


# ---------------------------------------------------------------- harness

def summarize(answers: list[Answer]) -> dict:
    def med(vals: list[float]) -> float:
        return statistics.median(vals) if vals else float("nan")

    # Latency medians cover completed answers only (errors/timeouts are
    # reported and count against accuracy, but a 0.0s not-attempted wall
    # must not deflate the median).
    by_kind: dict[str, dict] = {}
    for kind in ("defs", "callers", "literal"):
        sub = [a for a in answers if a.kind == kind]
        sub_ok = [a for a in sub if not a.error]
        by_kind[kind] = {
            "n": len(sub),
            "correct": sum(a.correct for a in sub),
            "median_wall_ms": round(med([a.wall_s for a in sub_ok]) * 1000, 3),
            "median_bytes": med([a.bytes for a in sub_ok]),
        }
    ok = [a for a in answers if not a.error]
    total_bytes = sum(a.bytes for a in answers)
    return {
        "accuracy": f"{sum(a.correct for a in answers)}/{len(answers)}",
        "correct": sum(a.correct for a in answers),
        "n": len(answers),
        "median_wall_ms": round(med([a.wall_s for a in ok]) * 1000, 3),
        "mean_bytes_per_answer": round(total_bytes / len(answers), 1) if answers else 0,
        "mean_tokens_per_answer_proxy": round(total_bytes / len(answers) / 4, 1) if answers else 0,
        "errors": [f"{a.qid}: {a.error}" for a in answers if a.error],
        "by_kind": by_kind,
    }


# Pure-scan tools: must finish before fszero cold index creates .fszero in the tree.
PURE_SCAN_TOOLS = ("rg", "grep", "fff", "bm25-rag")
FSZERO_QUERY_TOOLS = ("fszero-server", "fszero-spawn")
# Canonical fixed order (legacy / dual forward leg).
CANONICAL_PURE_ORDER = list(PURE_SCAN_TOOLS)


def maybe_drop_page_cache() -> dict[str, object]:
    """Best-effort OS page-cache drop between tools (opt-in).

    Set FSZERO_BAKEOFF_PURGE=1 to attempt. macOS `purge` often needs root and is
    skipped without it; Linux drop_caches needs CAP_SYS_ADMIN. Never fails the run.
    """
    if os.environ.get("FSZERO_BAKEOFF_PURGE", "").strip() not in ("1", "true", "yes"):
        return {"attempted": False, "reason": "FSZERO_BAKEOFF_PURGE not set"}
    if sys.platform == "darwin":
        try:
            r = subprocess.run(["purge"], capture_output=True, text=True, timeout=120)
            return {
                "attempted": True,
                "method": "purge",
                "rc": r.returncode,
                "stderr": (r.stderr or "")[:200],
            }
        except Exception as e:
            return {"attempted": True, "method": "purge", "error": repr(e)}
    if sys.platform.startswith("linux"):
        path = Path("/proc/sys/vm/drop_caches")
        try:
            path.write_text("3\n")
            return {"attempted": True, "method": "drop_caches=3", "ok": True}
        except Exception as e:
            return {"attempted": True, "method": "drop_caches", "error": repr(e)}
    return {"attempted": True, "reason": f"unsupported platform {sys.platform}"}


def pure_tool_orders(policy: str, n: int, n_shuffles: int) -> list[list[str]]:
    """Return one or more full pure-tool matrices for this size.

    - fixed: single canonical order (legacy bias; kept for A/B)
    - shuffle: n_shuffles independent seeded permutations (SEED, n, shuffle_i)
    - dual: canonical forward + reverse (conservative max of the two medians)
    """
    if policy == "fixed":
        return [list(CANONICAL_PURE_ORDER)]
    if policy == "dual":
        return [list(CANONICAL_PURE_ORDER), list(reversed(CANONICAL_PURE_ORDER))]
    if policy == "shuffle":
        orders: list[list[str]] = []
        for i in range(max(1, n_shuffles)):
            rng = random.Random((SEED * 1_000_003) ^ (n * 97) ^ (i * 0x9E3779B9))
            order = list(CANONICAL_PURE_ORDER)
            rng.shuffle(order)
            orders.append(order)
        return orders
    raise SystemExit(f"unknown order policy: {policy!r} (use fixed|shuffle|dual)")


def run_size(
    n: int,
    corpus: Path,
    cold_timeout: float,
    *,
    order_policy: str = "shuffle",
    order_shuffles: int = 1,
) -> dict:
    print(f"=== N={n}: generating corpus ...", flush=True)
    subprocess.run(
        ["python3", str(ROOT / "benchmarks" / "gen_corpus.py"),
         "--files", str(n), "--out", str(corpus), "--seed", str(SEED)],
        check=True,
    )
    actual = sum(1 for _ in corpus.rglob("*.rs"))
    if actual != n:
        raise SystemExit(f"INTEGRITY: corpus has {actual} files, expected {n}")
    questions = build_questions(corpus)
    if len(questions) != N_DEFS + N_CALLERS + N_LITERALS:
        raise SystemExit("INTEGRITY: question set incomplete")
    if (corpus / ".fszero").exists():
        raise SystemExit("INTEGRITY: fszero store present before baseline runs")

    size_result: dict = {
        "files": n,
        "questions": [asdict(q) for q in questions],
        "index_costs": {},
        "tools": {},
        "measurement_order": {
            "policy": order_policy,
            "order_shuffles_requested": order_shuffles,
            "pure_scan_constraint": (
                "pure-scan tools (rg/grep/fff/bm25-rag) always run before fszero cold "
                "index so no .fszero store exists while baselines scan the tree"
            ),
            "page_cache_purge": (
                "opt-in via FSZERO_BAKEOFF_PURGE=1 between pure tools; not assumed"
            ),
            "publish_guidance": (
                "for competitor medians prefer order_policy=shuffle with "
                "order_shuffles>=3, or dual (forward+reverse, conservative max median)"
            ),
            "matrices": [],
        },
    }

    def record(tool: str, answers: list[Answer], *, tag: str | None = None) -> dict:
        entry = {
            "summary": summarize(answers),
            "answers": [asdict(a) for a in answers],
        }
        if tag is not None:
            entry["matrix_tag"] = tag
        s = entry["summary"]
        label = f"{tool}" if tag is None else f"{tool}[{tag}]"
        print(f"  {label}: acc={s['accuracy']} median={s['median_wall_ms']}ms "
              f"tokens/answer~{s['mean_tokens_per_answer_proxy']}", flush=True)
        return entry

    def run_one_pure(tool: str) -> tuple[list[Answer], dict[str, object]]:
        extra: dict[str, object] = {}
        if tool == "rg":
            return [run_rg(corpus, q) for q in questions], extra
        if tool == "grep":
            return [run_grep(corpus, q) for q in questions], extra
        if tool == "fff":
            fff = FffTool(corpus)
            extra["fff_scan_s"] = round(fff.scan_s, 4)
            answers = [fff.run(q) for q in questions]
            fff.close()
            return answers, extra
        if tool == "bm25-rag":
            rag = Bm25Rag(corpus)
            extra["bm25_rag_build_s"] = round(rag.build_s, 4)
            return [rag.run(q) for q in questions], extra
        raise SystemExit(f"unknown pure tool: {tool}")

    orders = pure_tool_orders(order_policy, n, order_shuffles)
    # tool -> list of (summary-bearing entries) across matrices
    pure_runs: dict[str, list[dict]] = {t: [] for t in PURE_SCAN_TOOLS}
    purge_log: list[dict[str, object]] = []

    for mi, order in enumerate(orders):
        tag = f"m{mi}"
        print(f"--- N={n}: pure-scan matrix {mi + 1}/{len(orders)} order={order}", flush=True)
        size_result["measurement_order"]["matrices"].append({
            "index": mi,
            "order": list(order),
        })
        for ti, tool in enumerate(order):
            if ti > 0:
                purge_log.append(maybe_drop_page_cache())
            answers, extra = run_one_pure(tool)
            for k, v in extra.items():
                # Keep first observed index cost; matrices share corpus.
                size_result["index_costs"].setdefault(k, v)
            pure_runs[tool].append(record(tool, answers, tag=tag))

    size_result["measurement_order"]["purge_attempts"] = purge_log

    def conservative_pick(runs: list[dict]) -> dict:
        """When multiple matrices exist, publish the worse (higher) median wall.

        Accuracy must match across matrices for the same tool/questions; if not,
        keep the lower accuracy (honest) and still use the max median wall.
        """
        if len(runs) == 1:
            return {
                "summary": runs[0]["summary"],
                "answers": runs[0]["answers"],
                "matrices": 1,
                "aggregation": "single_matrix",
            }
        # max median wall = conservative vs page-cache favoritism
        by_wall = max(runs, key=lambda r: r["summary"]["median_wall_ms"])
        # min accuracy fraction
        def acc_frac(r: dict) -> float:
            a = r["summary"]["accuracy"]  # "k/n"
            k, nn = a.split("/")
            return int(k) / max(1, int(nn))
        by_acc = min(runs, key=acc_frac)
        picked = {
            "summary": dict(by_wall["summary"]),
            "answers": by_wall["answers"],
            "matrices": len(runs),
            "aggregation": "conservative_max_median_wall",
            "per_matrix_median_wall_ms": [
                r["summary"]["median_wall_ms"] for r in runs
            ],
            "per_matrix_accuracy": [r["summary"]["accuracy"] for r in runs],
        }
        if by_acc["summary"]["accuracy"] != by_wall["summary"]["accuracy"]:
            picked["summary"] = dict(by_wall["summary"])
            picked["summary"]["accuracy"] = by_acc["summary"]["accuracy"]
            picked["summary"]["accuracy_note"] = (
                "accuracy taken from lowest-accuracy matrix; wall from highest-median matrix"
            )
        return picked

    for tool in PURE_SCAN_TOOLS:
        size_result["tools"][tool] = conservative_pick(pure_runs[tool])
        s = size_result["tools"][tool]["summary"]
        print(f"  {tool} [published]: acc={s['accuracy']} median={s['median_wall_ms']}ms "
              f"agg={size_result['tools'][tool]['aggregation']}", flush=True)

    print(f"--- N={n}: fszero cold index (ONE run, timeout {cold_timeout:.0f}s)", flush=True)
    cold = fszero_cold_index(corpus, n, cold_timeout)
    size_result["index_costs"]["fszero_cold"] = cold
    if cold.get("timeout"):
        print(f"  fszero cold index TIMED OUT after {cold_timeout:.0f}s", flush=True)
    else:
        print(f"  fszero cold index: {cold['total_ms'] / 1000:.1f}s", flush=True)

    print(f"--- N={n}: fszero warm server", flush=True)
    server = FszeroServer(corpus, n)
    t0 = time.perf_counter()
    try:
        server.execute(fszero_plan(Question("prime", "literal", "zzzz_priming_no_match", "-")),
                       timeout_s=PRIMING_TIMEOUT_S)
        priming_s: float | str = round(time.perf_counter() - t0, 4)
    except Exception as e:
        # Publish the honest failure instead of aborting the whole run.
        priming_s = f"FAILED after {time.perf_counter() - t0:.0f}s: {e!r}"
        server.close()
        server = FszeroServer(corpus, n)
    size_result["index_costs"]["fszero_warm_open_s"] = round(server.start_s, 4)
    size_result["index_costs"]["fszero_warm_first_search_s"] = priming_s
    # A timeout corrupts the stdio stream (the late response would interleave
    # with the next request), so restart the server after one. The circuit
    # breaker is scoped PER QUESTION KIND: 2 consecutive timeouts on a kind
    # mark that kind's remaining questions not-attempted (counted incorrect,
    # never dropped) without denying the other kinds their attempts.
    answers = []
    kind_timeouts: dict[str, int] = {}
    for q in questions:
        if kind_timeouts.get(q.kind, 0) >= 2:
            answers.append(Answer(
                q.qid, q.kind, 0.0, 0, False,
                f"not attempted: circuit-broken after 2 timeouts ({RPC_READ_TIMEOUT_S:.0f}s cap)"
                f" on '{q.kind}' questions"))
            continue
        a = server.run(q)
        answers.append(a)
        if a.error and "timeout" in a.error:
            kind_timeouts[q.kind] = kind_timeouts.get(q.kind, 0) + 1
            server.close()
            server = FszeroServer(corpus, n)
    size_result["tools"]["fszero-server"] = record("fszero-server", answers)
    server.close()

    print(f"--- N={n}: fszero fresh process per query", flush=True)
    answers = []
    kind_timeouts = {}
    for q in questions:
        if kind_timeouts.get(q.kind, 0) >= 2:
            answers.append(Answer(
                q.qid, q.kind, 0.0, 0, False,
                f"not attempted: circuit-broken after 2 timeouts ({RPC_READ_TIMEOUT_S:.0f}s cap)"
                f" on '{q.kind}' questions"))
            continue
        a = run_fszero_spawn(corpus, n, q)
        answers.append(a)
        if a.error and "timeout" in a.error:
            kind_timeouts[q.kind] = kind_timeouts.get(q.kind, 0) + 1
    size_result["tools"]["fszero-spawn"] = record("fszero-spawn", answers)
    size_result["measurement_order"]["fszero_query_order"] = list(FSZERO_QUERY_TOOLS)
    return size_result


