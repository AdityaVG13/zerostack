        "",
        "Corpora: deterministic synthetic rust-like trees (`gen_corpus.py`, seed 42)."
        " 20 seeded questions per corpus (8 'which file defines fn X', 4 'which file"
        " calls X', 8 'find the string L'), derived from corpus structure, never"
        " hand-tuned. Correct iff the tool's agent-visible output contains the"
        " ground-truth relative path. Tokens per answer = bytes / 4 (stated proxy;"
        " no tokenizer invoked). Every question runs once per tool -- no retries,"
        " no dropped cases.",
        "",
        "Tool surfaces: fszero via its real MCP stdio surface (bytes = raw JSON-RPC"
        " response line), measured both as a warm long-lived server and as a fresh"
        " process per query; rg/grep spawn per query (their normal model); fff via"
        " its official Python SDK in-process (no CLI exists); bm25-rag returns its"
