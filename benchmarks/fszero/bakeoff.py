"""Head-to-head bake-off: FSZero vs fff vs ripgrep vs grep vs a code-RAG baseline.

Same workload for every tool (fszero-4d2):
  1. fresh/cold index cost on pinned corpora (gen_corpus.py, seed 42),
  2. per-query latency for defs / callers / grep-style questions,
  3. answer QUALITY on a fixed, seeded 20-question set (correct iff the
     tool's output contains the ground-truth relative file path),
  4. agent-visible bytes per answer (tokens proxied as bytes / 4 -- stated
     openly; no tokenizer is invoked).

Integrity (docs/benchmark-integrity.md): corpora generated by committed
script, question set seeded from corpus structure (not hand-tuned), every
question recorded including errors and losses, no retries, identical
questions for every tool, integrity violations abort the run rather than
publish a lie.

Tool notes:
  - fszero runs on its real agent surface (`--mode=codemode` MCP stdio);
    agent-visible bytes = the raw JSON-RPC tools/call response line.
    Measured twice: warm long-lived server (its intended mode) and a fresh
    process per query (parity with rg/grep spawn model).
  - fff has no one-shot CLI by design ("FFF is a file search library, not a
    CLI"); it runs through its official Python SDK in-process, its intended
    long-lived mode. Bytes = rendered "path:line: content" match lines.
  - bm25-rag is a documented simpler stand-in for an embedding code-RAG
    pipeline: rank-bm25 over 40-line chunks, top-5 chunks returned as the
    injected context. Its index build cost is measured; a real embedding
    pipeline's build cost (model download + per-chunk inference) is strictly
    higher, so this baseline flatters RAG on build cost.

Usage: uv run benchmarks/bakeoff.py [--sizes 2000,23000] [--cold-timeout 10800]
"""
