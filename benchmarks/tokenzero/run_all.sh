#!/usr/bin/env bash
# TokenZero benchmark suite: single entry point.
# Runs every benchmark in benchmarks/, records machine + tool versions, and
# regenerates docs/benchmarks.md (default) or a caller-specified file.
#
#   benchmarks/run_all.sh [output.md]
#
# Honesty policy: every published number states the exact command, tool
# version, corpus, and machine; missing tools are recorded, never skipped
# silently; central tendency AND spread (p50/p90/p99 or median/best) are
# reported, never best-of.
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"; cd "$ROOT" || exit 1
OUT="${1:-$ROOT/docs/benchmarks.md}"
H=(python3 "$ROOT/benchmarks/harness.py")
RUNS="${RUNS:-5}"; WARMUP="${WARMUP:-1}"; export RUNS WARMUP

log() { printf '[run_all] %s\n' "$*" >&2; }

BIN="$("${H[@]}" resolve_bin 2>/dev/null)" || { echo "ERROR: tokenzero binary not found. Set TOKENZERO_BIN=/path/to/tokenzero" >&2; exit 1; }
log "binary: $BIN"

{
  printf '# TokenZero Benchmarks\n\n'
  printf 'Regenerated by `benchmarks/run_all.sh`. Every number below comes from a\n'
  printf 'real run of the command shown; re-run the suite yourself to reproduce.\n\n'

  printf '## Run provenance\n\n'
  printf -- '- date (UTC): %s\n' "$(date -u '+%Y-%m-%d %H:%M:%S')"
  printf -- '- commit: %s\n' "$(git rev-parse --short HEAD 2>/dev/null || echo unknown)"
  printf -- '- machine: %s\n' "$(uname -srm)"
  if [[ "$(uname -s)" == Darwin ]]; then
    printf -- '- chip: %s\n' "$(sysctl -n machdep.cpu.brand_string 2>/dev/null || echo unknown)"
  fi
  printf -- '- tokenzero: `%s` (%s)\n' "$BIN" "$("$BIN" --version 2>&1 | head -1)"
  if [[ -x "$ROOT/target/release/tokenzero-codemode" ]]; then
    printf -- '- tokenzero-codemode: `target/release/tokenzero-codemode` (built from this commit)\n'
  fi
  for tool in rtk lean-ctx headroom ztk context-mode hyperfine; do
    if command -v "$tool" >/dev/null 2>&1; then
      printf -- '- %s: %s\n' "$tool" "$({ "$tool" --version || "$tool" version; } 2>&1 | head -1)"
    else
      printf -- '- %s: not installed (rows report `not installed`, never fabricated)\n' "$tool"
    fi
  done
  printf -- '- runs/cell: RUNS=%s WARMUP=%s (override via env)\n\n' "$RUNS" "$WARMUP"

  run_section() {
    local title="$1" blurb="$2"; shift 2
    printf '\n## %s\n\n%s\n\n' "$title" "$blurb"
    log "running: $title"
    if out=$("$@" 2>>/tmp/tz-runall-err.$$.log); then
      printf '%s\n' "$out"
    else
      [[ -n "$out" ]] && printf '%s\n\n' "$out"
      printf '_Benchmark exited nonzero; partial stdout is retained above and stderr was captured in the suite log.\n'
      printf 'Failure is reported rather than omitted (honesty policy)._\n'
      log "FAILED: $title"
    fi
  }

  run_section 'CLI cold read (process + first read/expand latency)' \
    'Command: `benchmarks/cli-cold-read.sh`. Cold = recovery cache removed per cell; warm = cache retained.' \
    bash "$ROOT/benchmarks/cli-cold-read.sh"

  run_section 'Token savings vs alternatives (competitor bake-off)' \
    'Command: `benchmarks/competitor-bakeoff.sh`. Same corpus and captured-stdout surface per task. Every TokenZero/raw pair uses `estimator:bytes-ceil-div4/v1`; this heuristic is not Q99. The grep row is explicitly warm/dedup after one untimed isolated-cache primer. The suite exits nonzero on any never-worse violation.' \
    bash "$ROOT/benchmarks/competitor-bakeoff.sh"

  run_section 'Large-repo navigation (million-line synthetic repo)' \
    'Command: `benchmarks/million-line-nav.sh`. 1000-file synthetic repo with a planted needle. Never-worse uses `visible-payload-bytes/v1` (JSON envelope excluded) and `estimator:bytes-ceil-div4/v1`; this heuristic is not Q99. Expand is integrity-only and is not summed into the gate. The script exits nonzero on task failure, invalid gate evidence, or any TokenZero row worse than raw.' \
    bash "$ROOT/benchmarks/million-line-nav.sh"

} > "$OUT"

log "wrote $OUT"
